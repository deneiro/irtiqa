export function translate(lang: Lang, key: Key, params?: Record<string, string | number>): string {
  let s = DICT[lang][key] ?? en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export interface T {
  lang: Lang;
  t: (key: Key, params?: Record<string, string | number>) => string;
  zone: (z: Zone | string) => string;
  themeLabel: (name: string) => string;
  themeShort: (name: string, fallback: string) => string;
  themeBlurb: (name: string, fallback: string) => string;
  relDate: (d: string | undefined) => string;
  monthLabel: (yyyyMm: string) => string;
  locale: string;
}

export function useT(): T {
  const { lang } = useStore();
  const t: T["t"] = (key, params) => translate(lang, key, params);
  const locale = lang === "ru" ? "ru-RU" : "en-GB";
  return {
    lang,
    t,
    zone: (z) => translate(lang, (`z_${z}` as Key) in en ? (`z_${z}` as Key) : "z_other"),
    themeLabel: (name) => THEME_LABELS[lang][name]?.label ?? name,
    themeShort: (name, fb) => THEME_LABELS[lang][name]?.short ?? fb,
    themeBlurb: (name, fb) => THEME_LABELS[lang][name]?.blurb ?? fb,
    relDate: (d) => {
      if (!d) return "—";
      const ts = Date.parse(d);
      if (Number.isNaN(ts)) return "—";
      const n = Math.floor((Date.now() - ts) / 86400000);
      if (n <= 0) return t("today");
      if (n === 1) return t("yesterday");
      if (n < 30) return t("d_ago", { n });
      if (n < 365) return t("mo_ago", { n: Math.floor(n / 30) });
      return t("y_ago", { n: (n / 365).toFixed(1) });
    },
    monthLabel: (k) => {
      const s = new Date(k + "-01T00:00:00").toLocaleDateString(locale, { month: "long", year: "numeric" });
      return s.charAt(0).toUpperCase() + s.slice(1);
    },
    locale,
  };
}
